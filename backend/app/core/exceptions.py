from typing import Any

from fastapi import FastAPI, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field
from starlette.exceptions import HTTPException as StarletteHTTPException


class ProblemDetail(BaseModel):
    """RFC 7807 Problem Details for HTTP APIs."""

    type: str = Field(
        default="about:blank",
        description="URI reference that identifies the problem type",
    )
    title: str = Field(description="Short, human-readable summary of the problem type")
    status: int = Field(description="HTTP status code generated by the origin server")
    detail: str = Field(description="Human-readable explanation specific to this occurrence")
    instance: str | None = Field(
        default=None, description="URI reference that identifies the specific occurrence"
    )
    extra: dict[str, Any] | None = Field(
        default=None, description="Additional problem-specific fields"
    )


class AppException(Exception):
    """Base application exception with HTTP status and problem detail."""

    def __init__(
        self,
        status_code: int,
        detail: str,
        type_: str = "about:blank",
        title: str | None = None,
        instance: str | None = None,
        extra: dict[str, Any] | None = None,
    ):
        self.status_code = status_code
        self.detail = detail
        self.type = type_
        self.title = title or self._default_title(status_code)
        self.instance = instance
        self.extra = extra
        super().__init__(detail)

    @staticmethod
    def _default_title(status_code: int) -> str:
        titles = {
            400: "Bad Request",
            401: "Unauthorized",
            403: "Forbidden",
            404: "Not Found",
            409: "Conflict",
            422: "Unprocessable Entity",
            429: "Too Many Requests",
            500: "Internal Server Error",
        }
        return titles.get(status_code, "Error")

    def to_problem_detail(self, request: Request | None = None) -> ProblemDetail:
        """Convert to ProblemDetail model."""
        instance = self.instance or (str(request.url) if request else None)
        return ProblemDetail(
            type=self.type,
            title=self.title,
            status=self.status_code,
            detail=self.detail,
            instance=instance,
            extra=self.extra,
        )


class ValidationException(AppException):
    """Validation error exception (422)."""

    def __init__(
        self,
        detail: str,
        errors: list[dict] | None = None,
        instance: str | None = None,
    ):
        super().__init__(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=detail,
            type_="https://tools.ietf.org/html/rfc7231#section-6.5.1",
            title="Validation Error",
            instance=instance,
            extra={"errors": errors} if errors else None,
        )


